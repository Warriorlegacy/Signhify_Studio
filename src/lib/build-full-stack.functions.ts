import { createServerFn } from "@tanstack/react-start";
import { requireSupabaseAuth } from "@/integrations/supabase/auth-middleware";
import { generateAIResponse } from "./ai-gateway.server";
import { resolveAIAccess } from "./ai-access.server";
import { withByokKeys } from "./byok-middleware";
import JSZip from "jszip";

export const buildFullStackApp = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth, withByokKeys])
  .inputValidator((input: unknown) => {
    const obj = (input ?? {}) as Record<string, unknown>;
    const prompt = typeof obj.prompt === "string" ? obj.prompt.slice(0, 4000) : "";
    const planText = typeof obj.planText === "string" ? obj.planText.slice(0, 12000) : "";
    if (!prompt) throw new Error("Prompt required.");
    return { prompt, planText };
  })
  .handler(async ({ data, context }) => {
    const { prompt, planText } = data;
    const { supabase, userId, claims } = context as {
      supabase: any;
      userId: string;
      claims?: { email?: string | null };
    };
    const byokClientKeys = (context as { byokClientKeys?: Record<string, string> }).byokClientKeys;
    // Gate before doing any AI work: free users must BYOK, paid/admin proceed.
    // BYOKRequiredError bubbles up to the client with an actionable message.
    await resolveAIAccess({ supabase, userId, email: claims?.email ?? null, byokClientKeys });

    // We'll generate the file tree step by step
    const zip = new JSZip();

    // 1. Generate README.md
    const readmeContent = await generateREADME(prompt, planText);
    zip.file("README.md", readmeContent);

    // 2. Generate package.json
    const packageJsonContent = await generatePackageJson(prompt, planText);
    zip.file("package.json", packageJsonContent);

    // 3. Generate tsconfig.json
    const tsconfigContent = await generateTsconfig(prompt, planText);
    zip.file("tsconfig.json", tsconfigContent);

    // 4. Generate vite.config.ts
    const viteConfigContent = await generateViteConfig(prompt, planText);
    zip.file("vite.config.ts", viteConfigContent);

    // 5. Generate Supabase migration
    const migrationContent = await generateSupabaseMigration(prompt, planText);
    zip.file("supabase/migrations/20260613000000_init.sql", migrationContent);

    // 6. Generate src/lib/supabase.ts
    const supabaseClientContent = await generateSupabaseClient(prompt, planText);
    zip.file("src/lib/supabase.ts", supabaseClientContent);

    // 7. Generate src/routes/index.tsx (home page)
    const homePageContent = await generateHomePage(prompt, planText);
    zip.file("src/routes/index.tsx", homePageContent);

    // 8. Generate src/routes/items/ (if applicable)
    // We'll check if the plan suggests a list of items
    const { itemsRoute, itemsApi } = await generateItemsCRUD(prompt, planText);
    if (itemsRoute) {
      zip.file("src/routes/items/index.tsx", itemsRoute);
    }
    if (itemsApi) {
      zip.file("src/routes/items/$itemId.tsx", itemsApi);
    }

    // 9. Generate src/lib/functions/items.server.ts
    const itemsServerContent = await generateItemsServer(prompt, planText);
    zip.file("src/lib/functions/items.server.ts", itemsServerContent);

    // Generate the zip as base64
    const zipBase64 = await zip.generateAsync({ type: "base64" });
    const downloadUrl = `data:application/zip;base64,${zipBase64}`;

    return {
      success: true,
      downloadUrl,
      fileSizeMb: (zipBase64.length * 0.75) / (1024 * 1024),
      expiresAt: new Date(Date.now() + 24 * 60 * 60 * 1000).toISOString(),
    };
  });

async function generateREADME(prompt: string, planText: string): Promise<string> {
  const SYSTEM = `You are Signhify AI's documentation writer. Generate a clear, concise README.md for a full-stack TanStack Start application based on the user's prompt and plan.`;
  const user = `
User prompt:
${prompt}

Plan context:
${planText}

Generate a README.md that includes:
- Project title and description
- Features
- Tech stack
- Setup instructions (npm install, npx supabase start, etc.)
- Deployment instructions
`;
  const content = await generateAIResponse({
    messages: [
      { role: "system", content: SYSTEM },
      { role: "user", content: user },
    ],
    temperature: 0.6,
    max_tokens: 1500,
  });
  return content.trim();
}

