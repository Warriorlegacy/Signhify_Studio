async function generateItemsCRUD(
  prompt: string,
  planText: string,
): Promise<{
  itemsRoute?: string;
  itemsApi?: string;
}> {
  // We'll use the AI to decide if a CRUD for items is needed and generate the files
  const SYSTEM = `You are Signhify AI's full-stack engineer. Based on the user's prompt and plan, determine if a CRUD interface for a resource (like items, tasks, etc.) is appropriate. If yes, generate the TanStack Start route files for:
  1. src/routes/items/index.tsx (list and create)
  2. src/routes/items/\$itemId.tsx (detail, update, delete)
  If not, return empty strings for both.
  `;
  const user = `
User prompt:
${prompt}

Plan context:
${planText}

If the plan describes a collection of items (e.g., tasks, products, users) that need to be created, read, updated, deleted, then generate the two files. Otherwise, indicate that no CRUD is needed.
  `;
  const content = await generateAIResponse({
    messages: [
      { role: "system", content: SYSTEM },
      { role: "user", content: user },
    ],
    temperature: 0.6,
    max_tokens: 2000,
  });

  // We expect the AI to return a JSON object with the two file contents or null
  try {
    const parsed = JSON.parse(content);
    return {
      itemsRoute: parsed.itemsRoute || undefined,
      itemsApi: parsed.itemsApi || undefined,
    };
  } catch {
    // If not JSON, assume no CRUD
    return { itemsRoute: undefined, itemsApi: undefined };
  }
}

